#!/usr/bin/env node
// build_file_index.mjs — the engine's list of every table file, generated.
//
//   node tools/build_file_index.mjs
//
// Reads data/manifest.json (the DE440 tables, 1550–2649) and
// data-far/manifest.json (the DE441 tables either side, 13,200 BC – AD
// 17,191) and writes src/generated/files.ts: each file's name, its exact TDB
// span and the JPL ephemeris it was fitted from. The engine chooses files by
// these spans, so a moment in the first days of January 2649 — still in the
// DE440 tables, which end mid-month — is never sent to the file after.
// Rerun after rebuilding either set of tables; test/files.test.ts fails if
// the index and the manifests disagree.

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = new URL("../", import.meta.url);
const read = (p) => JSON.parse(readFileSync(fileURLToPath(new URL(p, root)), "utf8"));
const near = read("data/manifest.json");
const far = read("data-far/manifest.json");

const files = [
  ...near.files.map((f) => ({ ...f, source: near.source.name, far: false })),
  ...far.files.map((f) => ({ ...f, source: far.source.name, far: true })),
].sort((a, b) => a.start_jd_tdb - b.start_jd_tdb);

for (let i = 1; i < files.length; i++) {
  if (files[i].start_jd_tdb !== files[i - 1].end_jd_tdb) {
    throw new Error(`gap or overlap between ${files[i - 1].name} and ${files[i].name}`);
  }
}

const rows = files.map((f) => `  [${JSON.stringify(f.name)}, ${f.start_jd_tdb}, ${f.end_jd_tdb}, ${f.far ? 1 : 0}],`);
const out = fileURLToPath(new URL("src/generated/files.ts", root));
writeFileSync(out, `// GENERATED by tools/build_file_index.mjs from data/manifest.json and
// data-far/manifest.json — do not edit. Rerun the tool instead.
//
// Every table file, in order, with no gap or overlap between neighbours:
// name, first and last TDB Julian Day it answers for [start, end), and whether
// it is one of the far tables (fitted from ${far.source.name}, ${files.length - near.files.length} files) rather than the
// DE440 tables in data/ (${near.files.length} files, fitted from ${near.source.name}).

/** The two JPL ephemerides the tables were fitted from. */
export const NEAR_SOURCE = ${JSON.stringify(near.source.name)};
export const FAR_SOURCE = ${JSON.stringify(far.source.name)};

// prettier-ignore
export const FILES: ReadonlyArray<readonly [name: string, start: number, end: number, far: 0 | 1]> = [
${rows.join("\n")}
];
`, "utf8");
console.log(`wrote ${files.length} files: ${files[0].name} (TDB ${files[0].start_jd_tdb}) .. ${files.at(-1).name} (TDB ${files.at(-1).end_jd_tdb})`);
