"""build_deltat.py — ΔT (TT − UT), measured where it has been measured, and
honestly uncertain where it has not.

Writes src/generated/deltat.ts: ΔT every quarter-year from 1549 to 2651, plus
when measurement ends, so the engine can say how sure it is of any date.

    python -I tools/build_deltat.py --finals /path/to/finals2000A.all

SOURCES, in the order Skyfield joins them (and this script uses Skyfield's own
construction, so the join is the published one, not a new invention):
  * 1973 to the present, and about a year of predictions: the IERS's daily
    Earth orientation series, finals2000A.all (IERS / US Naval Observatory,
    freely published). ΔT = 32.184 s + (TAI − UTC) − (UT1 − UTC).
  * Before 1973: the cubic splines of Morrison, Stephenson, Hohenkerk &
    Zawilski (2021), the update of Stephenson, Morrison & Hohenkerk (2016),
    fitted to eclipse and occultation records.
  * After the predictions: a spline from the present rate into the long-term
    parabola of Stephenson et al. (2016), ΔT = −320 + 32.5 u² s,
    u = (year − 1825) / 100.

THE FUTURE IS A GUESS. Nobody can know how fast the Earth will turn in 2300.
Published models disagree by minutes by 2400, which moves the Moon by
arcminutes and the Ascendant by about a degree. The table therefore carries an
uncertainty: zero to the millisecond where measured, growing as the square of
the years past the last measurement, reaching ±240 s in 2400 (the spread
between published models there).
"""
import argparse, os
import numpy as np
from skyfield.api import Loader

ap = argparse.ArgumentParser()
ap.add_argument("--finals", required=True, help="path to finals2000A.all")
args = ap.parse_args()

folder, name = os.path.split(os.path.abspath(args.finals))
assert name == "finals2000A.all", "Skyfield looks for the file by this name"
ts = Loader(folder, expire=False).timescale(builtin=False)

# Where measurement ends: the last row the IERS flags as measured ("I").
lines = open(args.finals, encoding="ascii", errors="replace").read().splitlines()
flags = [(int(float(l[7:15])), l[57]) for l in lines if len(l) > 68 and l[57] in "IP"]
measured_mjd = max(m for m, f in flags if f == "I")
predicted_mjd = max(m for m, f in flags if f == "P")
measured_jd = measured_mjd + 2400000.5
predicted_jd = predicted_mjd + 2400000.5

START = 2286820.25  # 1549-01-01 UT
STEP = 365.25 / 4
N = int((2689696.75 - START) / STEP) + 2  # through 2651-01-01
jd = START + STEP * np.arange(N)
dt = np.array([ts.ut1_jd(j).delta_t for j in jd])

# Quarter-year samples interpolated by cubic Hermite must reproduce the model
# between samples; check at random instants across the span.
rng = np.random.default_rng(1)
probe = rng.uniform(jd[1], jd[-2], 4000)

def hermite(x):
    i = np.floor((x - START) / STEP).astype(int)
    u = (x - (START + i * STEP)) / STEP
    p0, p1, p2, p3 = dt[i - 1], dt[i], dt[i + 1], dt[i + 2]
    m1, m2 = (p2 - p0) / 2, (p3 - p1) / 2
    return ((2 * u**3 - 3 * u**2 + 1) * p1 + (u**3 - 2 * u**2 + u) * m1
            + (-2 * u**3 + 3 * u**2) * p2 + (u**3 - u**2) * m2)

truth = np.array([ts.ut1_jd(j).delta_t for j in probe])
worst = np.abs(hermite(probe) - truth).max()
assert worst < 0.05, worst  # 50 ms moves the Moon 0.03″
print(f"{N} samples; interpolation within {worst*1000:.1f} ms of the model")

out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "generated", "deltat.ts")
values = ",".join(f"{v:.4f}" for v in dt)
with open(out, "w", encoding="utf-8", newline="\n") as f:
    f.write(f"""// GENERATED by tools/build_deltat.py — do not edit. Rerun the tool instead.
//
// ΔT = TT − UT in seconds, every quarter-year from 1549-01-01 UT. Measured
// (IERS) from 1973 to MEASURED_UNTIL; IERS predictions to PREDICTED_UNTIL;
// before 1973 the Morrison-Stephenson-Hohenkerk-Zawilski (2021) splines; after
// the predictions, a blend into the long-term parabola of Stephenson et al.
// (2016). Built from finals2000A.all with Skyfield's construction.

/** UT Julian Day of the first sample, and the spacing in days. */
export const DELTAT_START = {START};
export const DELTAT_STEP = {STEP};
/** The last day of measured Earth rotation in the source (UT Julian Day). */
export const MEASURED_UNTIL = {measured_jd};
/** The last day the IERS predicts (UT Julian Day); beyond it, a model. */
export const PREDICTED_UNTIL = {predicted_jd};

// prettier-ignore
export const DELTAT = [{values}] as const;
""")
print(f"measured until MJD {measured_mjd}, predicted until MJD {predicted_mjd}; wrote {out}")
