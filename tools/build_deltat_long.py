"""build_deltat_long.py — ΔT before 1549 and after 2651, for the DE441 tables.

src/generated/deltat.ts holds ΔT every quarter-year across the DE440 span
(tools/build_deltat.py). The DE441 tables reach 13,200 BC and AD 17,191, and
need ΔT there too. This writes src/generated/deltat-long.ts: two tables in
wider steps, one each side, from the same model and the same construction
(Skyfield's, from the same finals2000A.all):

  * before 1549: the cubic splines of Morrison, Stephenson, Hohenkerk &
    Zawilski (2021) back to 720 BC, then the long-term parabola of Stephenson,
    Morrison & Hohenkerk (2016), ΔT = −320 + 32.5 u² s, u = (year − 1825)/100;
  * after 2651: the blend into that same parabola.

Away from the present ΔT is a smooth curve, so a wide step loses nothing: the
cubic Hermite interpolation the engine uses is checked here against the model
at random instants, and the step is refused if it misses by 50 ms (which
would move the Moon 0.03″). By 13,200 BC ΔT is 8.5 DAYS; how uncertain it is
there is deltaTUncertainty's business, not this table's.

    python -I tools/build_deltat_long.py --finals /path/to/finals2000A.all
"""
import argparse, os, sys
import numpy as np
from skyfield.api import Loader

sys.stdout.reconfigure(encoding="utf-8")
ap = argparse.ArgumentParser()
ap.add_argument("--finals", required=True, help="path to finals2000A.all (the one deltat.ts was built from)")
args = ap.parse_args()
folder, name = os.path.split(os.path.abspath(args.finals))
assert name == "finals2000A.all", "Skyfield looks for the file by this name"
ts = Loader(folder, expire=False).timescale(builtin=False)

YEAR = 365.25
# Each side starts beyond the DE441 tables and overlaps the quarter-year table
# by several samples, so the engine always has two neighbours either side.
SIDES = {
    "PAST": {"from": -3101000.0, "to": 2290000.0, "step": 5 * YEAR},     # 13,203 BC .. 1557
    "FUTURE": {"from": 2685000.0, "to": 8002000.0, "step": 25 * YEAR},  # 2639 .. AD 17,196
}


def model(jd):
    return np.array([ts.ut1_jd(j).delta_t for j in np.atleast_1d(jd)])


def hermite(values, start, step, x):
    i = np.floor((x - start) / step).astype(int)
    u = (x - (start + i * step)) / step
    p0, p1, p2, p3 = values[i - 1], values[i], values[i + 1], values[i + 2]
    m1, m2 = (p2 - p0) / 2, (p3 - p1) / 2
    return ((2 * u**3 - 3 * u**2 + 1) * p1 + (u**3 - 2 * u**2 + u) * m1
            + (-2 * u**3 + 3 * u**2) * p2 + (u**3 - u**2) * m2)


out_lines = []
rng = np.random.default_rng(2)
for key, side in SIDES.items():
    start, step = side["from"], side["step"]
    n = int(np.ceil((side["to"] - start) / step)) + 1
    jd = start + step * np.arange(n)
    dt = model(jd)
    probe = rng.uniform(jd[1], jd[-2], 6000)
    worst = np.abs(hermite(dt, start, step, probe) - model(probe)).max()
    assert worst < 0.05, f"{key}: interpolation misses the model by {worst:.3f} s at a {step / YEAR:.0f}-year step"
    print(f"{key}: {n} samples every {step / YEAR:.0f} years; interpolation within {worst * 1000:.1f} ms of the model")
    values = ",".join(f"{v:.3f}" for v in dt)
    out_lines.append(f"""/** {key.lower()}: UT Julian Day of the first sample, and the spacing in days. */
export const DELTAT_{key}_START = {start};
export const DELTAT_{key}_STEP = {step};
// prettier-ignore
export const DELTAT_{key} = [{values}] as const;
""")

out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "generated", "deltat-long.ts")
with open(out, "w", encoding="utf-8", newline="\n") as f:
    f.write("""// GENERATED by tools/build_deltat_long.py — do not edit. Rerun the tool instead.
//
// ΔT = TT − UT in seconds, beyond the quarter-year table in deltat.ts: every
// 5 years back to 13,203 BC, every 25 years on to AD 17,196. Morrison-
// Stephenson-Hohenkerk-Zawilski (2021) splines back to 720 BC, the long-term
// parabola of Stephenson et al. (2016) beyond, by Skyfield's construction.

""" + "\n".join(out_lines))
print(f"wrote {out}")
